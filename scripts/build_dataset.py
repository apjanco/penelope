# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

MIN_OVERLAP_RATIO = 0.35          # passage grouping threshold (from consensus.py)
CONFIDENCE_RANK = {"high": 3, "medium": 2, "low": 1}
DEPRECATED_TYPES = {"soliloquy", "space_montage"}
NEG_WORDS_TARGET = 300            # approximate word count for Gutenberg negatives
# Placeholder think content for negative records.
# generate_traces.py will replace these with genuine skepticism-gate reasoning
# generated by a frontier model. Do not use for training without running that step.
NEG_THINK_STUB = (
    "This passage uses conventional narrative prose. "
    "The narrator describes events and states from outside character consciousness "
    "without rendering unmediated interior experience. "
    "No specific Humphrey/Steinberg marker is present. "
    "Skepticism gate: a passage of general narration or external description "
    "would look identical — no interior marker distinguishes this as SoC."
)

